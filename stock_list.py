def build_universe():
    stocks = []
    seen = set()
    for sector, members in STOCK_GROUPS.items():
        for idx, (code, name) in enumerate(members):
            if code in seen:
                continue
            seen.add(code)
            stocks.append(
                {
                    "code": code,
                    "name": name,
                    "sector": sector,
                    "exchange": "SH" if code.startswith(("6", "68")) else "SZ",
                    "board": "双创" if code.startswith(("3", "68")) else "主板",
                    "is_20cm": code.startswith(("3", "68")),
                    "index": idx,
                }
            )
    data_file = Path(__file__).resolve().parent / "data" / "mainboard_stocks.json"
    if data_file.exists():
        try:
            extra = json.loads(data_file.read_text(encoding="utf-8"))
        except Exception:
            extra = []
        for idx, item in enumerate(extra):
            code = str(item.get("code") or "")
            if not code or code in seen:
                continue
            seen.add(code)
            stocks.append(
                {
                    "code": code,
                    "name": str(item.get("name") or code),
                    "sector": str(item.get("sector") or "综合"),
                    "exchange": "SH" if code.startswith("6") else "SZ",
                    "board": "主板",
                    "is_20cm": False,
                    "index": idx,
                }
            )
    return stocks
